def show_menu():
    """
    显示主菜单选项
    功能：在控制台打印出所有可用的操作选项，供用户选择
    参数：无
    返回值：无（只负责打印信息）
    """
    print("1 添加联系人")
    print("2 查看联系人")
    print("3 删除联系人")
    print("0 退出")

def get_choice():
    """
    获取用户输入的选择
    功能：等待用户从键盘输入内容，并返回输入的结果
    参数：无
    返回值：用户输入的字符串（例如："1"、"2"、"3"、"0"）
    注意：这里不验证输入是否合法，只负责接收，验证在 run() 函数中进行
    """
    choice = input()                    # input() 会等待用户按回车，返回用户输入的内容（字符串类型）
    return choice                       # 将用户输入的内容返回给调用者

def show_contacts(contact_book):
    """
    显示当前通讯录中的所有联系人
    功能：遍历通讯录对象，打印每个联系人的姓名和电话
    参数：
        contact_book: ContactBook 类型的对象，包含所有联系人数据
    返回值：无（只负责打印信息）
    
    特殊情况处理：
        如果通讯录为空（没有任何联系人），打印提示信息后提前返回
    """
    # 检查通讯录是否为空
    # len() 函数会调用 contact_book 的 __len__() 方法
    # 注意：ContactBook 类必须先实现 __len__() 方法，否则 len() 会报错
    if len(contact_book) == 0:                # 检查特殊情况；len() 调用对象的 __len__() 方法，对于自定义类，需要先实现 __len__() 才支持 len()
        print("通讯录为空")
        return                                # ← 提前返回，不执行后续代码（return 用于提前结束函数执行）
    print("当前联系人：")

    # 遍历通讯录中的每一个联系人
    # for 循环会调用 contact_book 的 __iter__() 方法
    # 注意：ContactBook 类必须先实现 __iter__() 方法，否则无法遍历
    for contact in contact_book:                    # ← 遍历每个联系人
        # contact 是 Contact 类的实例对象
        # 通过 .name 和 .phone 属性获取联系人的姓名和电话
        print(contact.name, contact.phone)    # ← 每次迭代执行
    print("----------------")                 # ← 函数执行到这里自动结束，不需要 return

# ==================== 主业务循环 ====================
def run(contact_book):
    """
    主程序运行函数 - 整个通讯录的核心控制流程
    功能：显示菜单、处理用户输入、执行相应的操作，直到用户选择退出
    参数：
        contact_book: ContactBook 类型的对象，存储所有联系人数据
    返回值：无（程序退出时返回）
    
    这是一个无限循环（while True），只有用户输入 "0" 时才会退出
    """

    while True:
         # ===== 第1步：显示菜单 =====
        show_menu()                               # 调用 show_menu() 函数打印操作选项

        # ===== 第2步：获取用户选择 =====
        choice = get_choice()                     # 等待用户输入，返回的是字符串（如 "1", "2", "3", "0"）

        # ===== 第3步：根据用户选择执行对应操作 =====
        # ---------- 选项0：退出程序 ----------
        if choice == "0":                         # 字符串比较，不需要转数字，因为不涉及数学运算
            break                                 # break 会立即跳出 while 循环，结束程序

        # ---------- 选项1：添加联系人 ----------
        elif choice == "1":
            # 提示用户输入联系人的姓名和电话
            name = input("姓名：")                 # input() 会等待用户输入姓名
            phone = input("电话：")                # input() 会等待用户输入电话

            try:
                # 尝试执行添加操作（可能因为数据不合法而抛出异常）
                # add_contact() 方法会验证姓名是否为空、电话格式是否正确等
                contact_book.add_contact(name, phone)
            except ValueError as e:                  # as e	：将异常对象赋值给变量 e
                # 如果发生 ValueError 异常（数据不合法），执行这里的代码
                print(f"添加失败：{e}")
                continue                             # continue 会跳转到循环开始，重新显示菜单，不执行后面的"添加成功"
            # 如果 try 块没有抛出异常，说明添加成功 
            print("添加成功")

        # ---------- 选项2：查看联系人 ----------
        elif choice == "2":                     # 这里使用 elif 而不是 if，因为选择了"2"就不会再检查后续条件
            show_contacts(contact_book)         # 调用 show_contacts() 函数显示所有联系人
    
        # ---------- 选项3：删除联系人 ----------
        elif choice == "3":
            # 第1步：先显示所有联系人，让用户知道有哪些联系人可以删除
            show_contacts(contact_book)
            # 第2步：提示用户输入要删除的联系人编号
            number = input("请输入编号：")
            # 第3步：验证输入是否为数字
            # isdigit() 方法检查字符串是否只包含数字字符（如 "1", "23", "456"）
            if not number.isdigit():
                print("请输入数字")
                continue                                   # 回到循环开始，重新显示菜单，不执行后续的删除操作
            
            # 第4步：将字符串转换为整数（因为列表索引必须是整数）
            # 用户看到的是从1开始的编号（第1个、第2个...）
            # 但列表的索引是从0开始的（第0个、第1个...）
            number = int(number)                          # 作为索引使用，需要将字符串转换为整数（关键步骤）
            
            # 第5步：检查编号是否在有效范围内
            # 编号必须 >= 1 且 <= 通讯录的总人数
            if number < 1 or number > len(contact_book):
                print("编号无效")
                continue

            # 第6步：执行删除操作
            # 注意：用户输入的编号从1开始，但列表索引从0开始，所以需要减1
            # 例如：用户输入"1"表示删除第1个联系人，对应列表索引0
            contact_book.delete_contact(number - 1)
            print("删除成功")

